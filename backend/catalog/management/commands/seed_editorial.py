class Command(BaseCommand):
    help = "Добавляет реальные отзывы из предоставленного файла и первые авторские статьи, не перезаписывая правки."

    def handle(self, *args, **options):
        reviews = articles = 0
        for position, (key, author, text) in enumerate(REVIEWS, 1):
            _, created = Review.objects.get_or_create(source_key=key, defaults={"author": author, "text": text, "position": position, "source_url": AVITO, "is_published": True})
            reviews += created
        for slug, title, excerpt, offering_slug, body in ARTICLES:
            _, created = Article.objects.get_or_create(slug=slug, defaults={"title": title, "excerpt": excerpt, "body": body, "seo_description": excerpt, "related_offering": Offering.objects.filter(slug=offering_slug).first() if offering_slug else None, "is_published": True})
            articles += created
        self.stdout.write(f"Добавлено отзывов: {reviews}, статей: {articles}. Существующие записи сохранены.")
